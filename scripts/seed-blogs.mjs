const db = new DatabaseSync(dbPath);

console.log('🌱 Connected to SQLite via node:sqlite at:', dbPath);
console.log('🚀 Seeding authentic Persian SEO blog data into Payload CMS...');

// پاکسازی جداول قبلی مقالات
db.exec('DELETE FROM blogs_paragraphs;');
db.exec('DELETE FROM blogs_tags;');
db.exec('DELETE FROM blogs_rels;');
db.exec('DELETE FROM blogs;');

const insertBlog = db.prepare(`
  INSERT INTO blogs (
    id, title, slug, excerpt, category, reading_time, published_at,
    image_url, featured, status, author, reviewer, meta_title,
    meta_description, canonical_u_r_l, no_index, created_at, updated_at
  ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'published', ?, ?, ?, ?, ?, ?, datetime('now'), datetime('now'))
`);

const insertParagraph = db.prepare(`
  INSERT INTO blogs_paragraphs (_order, _parent_id, id, text)
  VALUES (?, ?, ?, ?)
`);

const insertTag = db.prepare(`
  INSERT INTO blogs_tags (_order, _parent_id, id, tag)
  VALUES (?, ?, ?, ?)
`);

BLOG_POSTS.forEach((post, index) => {
  insertBlog.run(
    post.id,
    post.title,
    post.slug,
    post.excerpt,
    post.category,
    post.readingTime,
    post.publishedAt,
    post.imageUrl,
    post.featured,
    post.author,
    post.reviewer,
    post.metaTitle,
    post.metaDescription,
    post.canonicalURL,
    post.noIndex
  );

  post.paragraphs.forEach((p, pIdx) => {
    insertParagraph.run(pIdx + 1, post.id, `${post.id}-p-${pIdx + 1}`, p);
  });

  post.tags.forEach((t, tIdx) => {
    insertTag.run(tIdx + 1, post.id, `${post.id}-t-${tIdx + 1}`, t);
  });

  console.log(`  ✅ Seeded article [${index + 1}/${BLOG_POSTS.length}]: ${post.title}`);
});

console.log('🎉 All 6 blog posts with full SEO fields successfully seeded into SQLite!');
db.close();
